def airports():
    return {a.ident: a for a in parse_apt(APT)}


def test_phraseology():
    assert say.digits(270) == "two seven zero"
    assert say.runway("07L") == "zero seven left"
    assert say.frequency(118505) == "one one eight decimal five zero five"
    assert say.frequency(118700) == "one one eight decimal seven"
    assert say.frequency(121000) == "one two one decimal zero"
    assert say.altitude(2500) == "two thousand five hundred"
    assert say.altitude(12000) == "one two thousand"
    assert say.signed(-2) == "minus two"
    assert say.zulu_time(14 * 3600 + 50 * 60) == "one four five zero"
    assert say.spoken_callsign("C-GTLT") == "Charlie Golf Tango Lima Tango"


def test_parse_apt_airports_runways_and_frequencies():
    found = airports()
    assert set(found) == {"EGGW", "KSEA"}  # heliport and runway-less strip are skipped
    luton = found["EGGW"]
    assert abs(luton.lat - 51.8747) < 1e-3 and luton.elev_ft == 520
    assert [(r.end1, r.end2) for r in luton.runways] == [("07", "25")]
    assert 2100 < luton.runways[0].length_m < 2250
    kinds = sorted((f.kind, f.khz) for f in luton.freqs)
    assert kinds == [("atis", 120580), ("ground", 121755), ("tower", 132555)]  # legacy 132.55 duplicate dropped
    assert found["KSEA"].spoken_name == "Seattle Tacoma"


def test_runway_selection_headwind_parallels_and_calm():
    found = airports()
    assert runways_in_use(found["EGGW"], 260, 12) == ["25"]
    assert runways_in_use(found["EGGW"], 80, 12) == ["07"]
    assert runways_in_use(found["KSEA"], 170, 10) == ["16L", "16R"]  # short crossing runway ignored
    assert runways_in_use(found["KSEA"], 270, 20) == ["34L", "34R"] or runways_in_use(found["KSEA"], 270, 20) == ["16L", "16R"]
    assert runways_in_use(found["EGGW"], 0, 0) == ["07"]


def test_atis_text_icao_and_faa_styles():
    found = airports()
    weather = Weather(
        wind_dir_true=262,
        wind_kt=12,
        visibility_sm=10,
        clouds=[Cloud(0.2, 2500), Cloud(0.7, 4000)],
        temperature_c=15,
        dewpoint_c=-1,
        qnh_hpa=1013.4,
    )
    text = compose(found["EGGW"], weather, "C", 14 * 3600 + 50 * 60, variation=-2)
    assert text.startswith("London Luton information Charlie, time one four five zero Zulu.")
    assert "Runway two five in use." in text
    assert "Wind two six zero degrees one two knots." in text
    assert "Visibility one zero kilometres or more." in text
    assert "Cloud few two thousand five hundred feet, broken four thousand feet." in text
    assert "Temperature one five, dewpoint minus one." in text
    assert "Q N H one zero one three." in text

    us = compose(found["KSEA"], Weather(wind_kt=0, visibility_sm=3, qnh_hpa=1013.25), "A", 0)
    assert uses_faa_style("KSEA") and not uses_faa_style("EGGW")
    assert "Wind calm." in us and "Visibility three." in us and "Sky clear." in us
    assert "Altimeter two niner niner two." in us
    assert "Advise on initial contact you have information Alfa." in us


def test_atis_letter_advances_only_when_weather_changes():
    luton = airports()["EGGW"]
    book = AtisBook()
    calm = Weather(wind_dir_true=250, wind_kt=8)
    first = book.current(luton, calm, 14 * 3600)
    assert first.letter == "O" and first.zulu_seconds == 14 * 3600
    # Small fluctuation: same information, still broadcasting the weather as issued.
    same, text = book.text(luton, Weather(wind_dir_true=262, wind_kt=11), 14 * 3600 + 600)
    assert same is first and "Wind two five zero degrees eight knots." in text
    changed = book.current(luton, Weather(wind_dir_true=70, wind_kt=15), 15 * 3600)
    assert changed.letter == "P" and changed.zulu_seconds == 15 * 3600
    assert book.current(luton, Weather(wind_dir_true=70, wind_kt=15, qnh_hpa=1011), 15 * 3600 + 60).letter == "Q"


def test_weather_from_snapshot_picks_surface_layer_and_agl_bases():
    state = {
        "wx_qnh_pas": 101800.0,
        "wx_visibility_sm": 6.0,
        "elevation_m": 160.0,
        "wx_oat_c": 11.0,
        "wx_wind_alt_m": [3000.0, 150.0, 9000.0],
        "wx_wind_kt": [40.0, 9.0, 80.0],
        "wx_wind_dir": [300.0, 240.0, 280.0],
        "wx_cloud_cover": [0.5, 0.02, 0.9],
        "wx_cloud_base_m": [1000.0, 2000.0, 100.0],
        "wx_cloud_type": [2.0, 0.0, 1.0],
        "wx_dewpoint_c": [14.0, 2.0],
    }
    weather = from_snapshot(state, field_elev_ft=520)
    assert (weather.wind_kt, weather.wind_dir_true) == (9.0, 240.0)
    assert round(weather.qnh_hpa) == 1018 and weather.temperature_c == 11.0
    assert weather.dewpoint_c == 11.0  # never above temperature
    assert len(weather.clouds) == 1  # thin layer and the one below field level are dropped
    assert 2700 < weather.clouds[0].base_ft_agl < 2800
    assert from_snapshot({}, 0) is None


def test_station_lookup_by_frequency_range_and_tolerance(tmp_path):
    apt = tmp_path / "apt.dat"
    apt.write_text("\n".join(APT), encoding="utf-8")
    db_path = tmp_path / "airports.sqlite"
    assert build_index(apt, db_path) == 2
    db = AirportDB(db_path)

    tower = db.station(132555, 51.88, -0.37)
    assert tower.callsign == "Luton Tower" and tower.place == "Luton" and tower.kind == "tower" and tower.distance_nm < 1
    assert db.station(121755, 51.88, -0.37).callsign == "London Luton Ground"  # label "GND" is not a callsign
    assert db.station(132550, 51.88, -0.37).kind == "tower"  # 25 kHz spelling of the same channel
    assert db.station(132555, 52.6, -0.37) is None  # 43 NM away: beyond tower range
    assert db.station(120580, 52.6, -0.37).kind == "atis"  # ATIS carries further
    assert db.station(121755, 52.1, -0.37) is None  # ground only near the field
    assert db.station(118505, 51.88, -0.37) is None
    assert [a.ident for _, a in db.nearest(51.9, -0.4, 30)] == ["EGGW"]

    facts = briefing(tower, Weather(wind_dir_true=262, wind_kt=12, qnh_hpa=1013.4), "C", variation=-2)
    assert facts["you_are"] == "Luton Tower" and facts["runway_in_use"] == ["25"]
    assert facts["surface_wind"] == "260 degrees 12 knots" and facts["qnh_hpa"] == 1013
    assert facts["current_atis"] == "Charlie" and facts["frequencies"]["ground (GND)"] == "121.755"


def test_station_callsign_from_sim_labels():
    from proatc.navdata import Station

    luton = airports()["EGGW"]

    def name(kind, label):
        station = Station(luton, kind, 118505, label, 0)
        return station.callsign, station.place

    assert name("tower", "Heathrow Tower 1") == ("Heathrow Tower", "Heathrow")
    assert name("atis", "Heathrow ATIS") == ("Heathrow Information", "Heathrow")
    assert name("approach", "Heathrow Director 4") == ("Heathrow Director", "Heathrow")
    assert name("approach", "APP/DEP") == ("London Luton Approach", "London Luton")
    assert name("tower", "TWR") == ("London Luton Tower", "London Luton")


def test_tuned_frequency_follows_com_selection_and_variation():
    assert tuned_khz({"com1_khz": 118505, "com2_khz": 121755}) == 118505
    assert tuned_khz({"com1_khz": 118505, "com2_khz": 121755, "com_selection": 7}) == 121755
    assert tuned_khz({}) is None
    assert magnetic_variation({"heading_mag": 1.0, "heading_true": 359.0}) == 2.0
